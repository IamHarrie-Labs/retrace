import fs from "node:fs";
import postcss from "postcss";

// Preserve the supplied page's actual component rules and responsive queries.
// Svelte-generated scoping is converted to explicit React component scopes.
const scopes = {
  "x35jl1": "source-slice-hero",
  "1cpv9bu": "source-slice-services",
  "jho2ao": "source-slice-case",
  "6u9x8t": "source-slice-table",
  "19icql0": "source-slice-onboarding",
};
const root = postcss.parse(fs.readFileSync("design/source-reference/index.CFDwdt-Q.css", "utf8"));
root.walkRules(rule => {
  const entry = Object.entries(scopes).find(([hash]) => rule.selector.includes(`svelte-${hash}`));
  if (!entry) { rule.remove(); return; }
  const [hash, scope] = entry;
  rule.selector = rule.selectors.map(selector => {
    const clean = selector.replaceAll(`:where(.svelte-${hash})`, "").replaceAll(`.svelte-${hash}`, "").replace(/\.hero(?=[\s.:#\[>+~]|$)/g, ".source-hero");
    return `.source-page .${scope} ${clean}`;
  }).join(",");
});
root.walkAtRules(rule => { if (!rule.nodes?.length) rule.remove(); });
root.prepend(postcss.comment({text:"Adapted directly from the stylesheet referenced by the user-supplied HTML. Generated by scripts/adapt-reference-css.mjs; Svelte scopes remapped for React. Product adjustments live in reference-theme.css."}));
fs.writeFileSync("src/app/reference-source.css", root.toString().replaceAll("}", "}\n"));
console.log(`Adapted ${root.nodes.length} source CSS blocks.`);
